def format_validation_error_fields(
    errors: list[dict[str, Any]],
) -> dict[str, str]:
    """Extract a dictionary of {field_name: message} from Pydantic/FastAPI validation errors."""
    fields: dict[str, str] = {}
    for err in errors:
        loc = err.get("loc", ())
        # Filter out "body" from loc if present
        parts = [str(p) for p in loc if p != "body"]
        field_name = parts[-1] if parts else "__root__"

        msg = err.get("msg", "Invalid value")
        # Strip internal Pydantic prefix "Value error, " for cleaner messages
        if msg.startswith("Value error, "):
            msg = msg[len("Value error, "):]

        fields[field_name] = msg
    return fields
